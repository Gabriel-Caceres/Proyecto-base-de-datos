```sql
CREATE TABLE ROLES (
    ID_ROL NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(50) NOT NULL,
    NIVEL_JERARQUIA NUMBER NOT NULL,
    DESCRIPCION VARCHAR2(200),

    CONSTRAINT PK_ROLES PRIMARY KEY (ID_ROL),
    CONSTRAINT UQ_ROLES_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT UQ_ROLES_JERARQUIA UNIQUE (NIVEL_JERARQUIA),
    CONSTRAINT CK_ROLES_JERARQUIA
        CHECK (NIVEL_JERARQUIA BETWEEN 1 AND 5)
);


CREATE TABLE TRABAJADORES (
    ID_TRABAJADOR NUMBER GENERATED BY DEFAULT AS IDENTITY,
    RUT VARCHAR2(12) NOT NULL,
    NOMBRE VARCHAR2(50) NOT NULL,
    APELLIDO VARCHAR2(50) NOT NULL,
    FECHA_CONTRATACION DATE NOT NULL,
    ID_ROL NUMBER NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_TRABAJADORES PRIMARY KEY (ID_TRABAJADOR),
    CONSTRAINT UQ_TRABAJADORES_RUT UNIQUE (RUT),
    CONSTRAINT FK_TRABAJADORES_ROL
        FOREIGN KEY (ID_ROL)
        REFERENCES ROLES(ID_ROL),
    CONSTRAINT CK_TRABAJADORES_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO', 'SUSPENDIDO'))
);


CREATE TABLE CAJAS (
    ID_CAJA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO_CAJA NUMBER NOT NULL,
    NOMBRE VARCHAR2(50) NOT NULL,
    TIPO VARCHAR2(20) NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVA' NOT NULL,

    CONSTRAINT PK_CAJAS PRIMARY KEY (ID_CAJA),
    CONSTRAINT UQ_CAJAS_NUMERO UNIQUE (NUMERO_CAJA),
    CONSTRAINT CK_CAJAS_TIPO
        CHECK (TIPO IN ('NORMAL', 'DELIVERY')),
    CONSTRAINT CK_CAJAS_ESTADO
        CHECK (ESTADO IN ('ACTIVA', 'INACTIVA', 'MANTENCION'))
);


CREATE TABLE TURNOS (
    ID_TURNO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(30) NOT NULL,

    CONSTRAINT PK_TURNOS PRIMARY KEY (ID_TURNO),
    CONSTRAINT UQ_TURNOS_NOMBRE UNIQUE (NOMBRE)
);


CREATE TABLE CATEGORIAS (
    ID_CATEGORIA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(50) NOT NULL,
    DESCRIPCION VARCHAR2(200),

    CONSTRAINT PK_CATEGORIAS PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UQ_CATEGORIAS_NOMBRE UNIQUE (NOMBRE)
);


CREATE TABLE PRODUCTOS (
    ID_PRODUCTO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    DESCRIPCION VARCHAR2(250),
    PRECIO NUMBER(10,2) NOT NULL,
    ID_CATEGORIA NUMBER NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'DISPONIBLE' NOT NULL,

    CONSTRAINT PK_PRODUCTOS PRIMARY KEY (ID_PRODUCTO),
    CONSTRAINT FK_PRODUCTOS_CATEGORIA
        FOREIGN KEY (ID_CATEGORIA)
        REFERENCES CATEGORIAS(ID_CATEGORIA),
    CONSTRAINT CK_PRODUCTOS_PRECIO
        CHECK (PRECIO >= 0),
    CONSTRAINT CK_PRODUCTOS_ESTADO
        CHECK (ESTADO IN ('DISPONIBLE', 'NO_DISPONIBLE'))
);


CREATE TABLE METODOS_PAGO (
    ID_METODO_PAGO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(50) NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_METODOS_PAGO PRIMARY KEY (ID_METODO_PAGO),
    CONSTRAINT UQ_METODOS_PAGO_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CK_METODOS_PAGO_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);


CREATE TABLE VENTAS (
    ID_VENTA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    FECHA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ID_TRABAJADOR NUMBER NOT NULL,
    ID_CAJA NUMBER NOT NULL,
    ID_METODO_PAGO NUMBER NOT NULL,
    SUBTOTAL NUMBER(12,2) NOT NULL,
    DESCUENTO NUMBER(12,2) DEFAULT 0 NOT NULL,
    TOTAL NUMBER(12,2) NOT NULL,

    CONSTRAINT PK_VENTAS PRIMARY KEY (ID_VENTA),
    CONSTRAINT FK_VENTAS_TRABAJADOR
        FOREIGN KEY (ID_TRABAJADOR)
        REFERENCES TRABAJADORES(ID_TRABAJADOR),
    CONSTRAINT FK_VENTAS_CAJA
        FOREIGN KEY (ID_CAJA)
        REFERENCES CAJAS(ID_CAJA),
    CONSTRAINT FK_VENTAS_METODO_PAGO
        FOREIGN KEY (ID_METODO_PAGO)
        REFERENCES METODOS_PAGO(ID_METODO_PAGO),
    CONSTRAINT CK_VENTAS_SUBTOTAL
        CHECK (SUBTOTAL >= 0),
    CONSTRAINT CK_VENTAS_DESCUENTO
        CHECK (DESCUENTO >= 0),
    CONSTRAINT CK_VENTAS_TOTAL
        CHECK (TOTAL >= 0),
    CONSTRAINT CK_VENTAS_CALCULO
        CHECK (TOTAL = SUBTOTAL - DESCUENTO)
);


CREATE TABLE DETALLE_VENTA (
    ID_DETALLE NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_VENTA NUMBER NOT NULL,
    ID_PRODUCTO NUMBER NOT NULL,
    CANTIDAD NUMBER NOT NULL,
    PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
    SUBTOTAL NUMBER(12,2) NOT NULL,

    CONSTRAINT PK_DETALLE_VENTA PRIMARY KEY (ID_DETALLE),
    CONSTRAINT FK_DETALLE_VENTA
        FOREIGN KEY (ID_VENTA)
        REFERENCES VENTAS(ID_VENTA),
    CONSTRAINT FK_DETALLE_PRODUCTO
        FOREIGN KEY (ID_PRODUCTO)
        REFERENCES PRODUCTOS(ID_PRODUCTO),
    CONSTRAINT CK_DETALLE_CANTIDAD
        CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DETALLE_PRECIO
        CHECK (PRECIO_UNITARIO >= 0),
    CONSTRAINT CK_DETALLE_SUBTOTAL
        CHECK (SUBTOTAL = CANTIDAD * PRECIO_UNITARIO)
);


CREATE TABLE TIPOS_SUGESTIVA (
    ID_TIPO_SUGESTIVA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(50) NOT NULL,
    DESCRIPCION VARCHAR2(200),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_TIPOS_SUGESTIVA
        PRIMARY KEY (ID_TIPO_SUGESTIVA),

    CONSTRAINT UQ_TIPOS_SUGESTIVA_NOMBRE
        UNIQUE (NOMBRE),

    CONSTRAINT CK_TIPOS_SUGESTIVA_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);


CREATE TABLE SUGESTIVAS_VENTA (
    ID_SUGESTIVA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_VENTA NUMBER NOT NULL,
    ID_TIPO_SUGESTIVA NUMBER NOT NULL,
    ID_PRODUCTO_ORIGINAL NUMBER,
    ID_PRODUCTO_SUGERIDO NUMBER,
    VALOR_ADICIONAL NUMBER(10,2) DEFAULT 0 NOT NULL,
    CANTIDAD NUMBER DEFAULT 1 NOT NULL,
    OBSERVACION VARCHAR2(250),

    CONSTRAINT PK_SUGESTIVAS_VENTA
        PRIMARY KEY (ID_SUGESTIVA),

    CONSTRAINT FK_SUGESTIVA_VENTA
        FOREIGN KEY (ID_VENTA)
        REFERENCES VENTAS(ID_VENTA),

    CONSTRAINT FK_SUGESTIVA_TIPO
        FOREIGN KEY (ID_TIPO_SUGESTIVA)
        REFERENCES TIPOS_SUGESTIVA(ID_TIPO_SUGESTIVA),

    CONSTRAINT FK_SUGESTIVA_PRODUCTO_ORIGINAL
        FOREIGN KEY (ID_PRODUCTO_ORIGINAL)
        REFERENCES PRODUCTOS(ID_PRODUCTO),

    CONSTRAINT FK_SUGESTIVA_PRODUCTO_SUGERIDO
        FOREIGN KEY (ID_PRODUCTO_SUGERIDO)
        REFERENCES PRODUCTOS(ID_PRODUCTO),

    CONSTRAINT CK_SUGESTIVA_VALOR
        CHECK (VALOR_ADICIONAL >= 0),

    CONSTRAINT CK_SUGESTIVA_CANTIDAD
        CHECK (CANTIDAD > 0)
);
